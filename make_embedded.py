#!/usr/bin/env python3
"""Generate tdc_embedded.h — built-in template pieces from the reference disk
(samples/2224_2_image). Regenerate: python3 make_embedded.py"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, 'samples', '2224_2_image')
OUT = os.path.join(HERE, 'tdc_embedded.h')
SIG = b'Copyright (C) KARL MAYER'

d = open(REF, 'rb').read()
# find LAENGE block via the simple known layout (block 391 for this disk)
e = d[4096:].find(b'\r\n\x00')
par = d[4096+e+3: 4096+e+3+90]
wbits = int.from_bytes(par[8:10], 'big')
laenge_blk = None
for off in range(0, 2048, 32):
    if d[off] == 0 and d[off+1:off+12] == b'LAENGE  FAC':
        laenge_blk = int.from_bytes(d[off+16:off+18], 'little')
        break
assert laenge_blk, 'LAENGE record not found'
lblk = d[laenge_blk*2048:(laenge_blk+1)*2048]
ci = lblk.find(SIG)
laenge = lblk[:ci]
content_end = e+3+90 + int.from_bytes(par[14:16],'big') * (int.from_bytes(par[21:23],'little'))
inblk = content_end % 2048
trailer = d[4096+content_end: 4096+content_end + min(1868, 2048-inblk)]

def carr(name, data, kind='uint8_t'):
    lines = [f'static const {kind} {name}[{len(data)}] = {{']
    for i in range(0, len(data), 16):
        chunk = ','.join(f'0x{b:02x}' for b in data[i:i+16])
        lines.append('    ' + chunk + ',')
    lines.append('};')
    return '\n'.join(lines)

with open(OUT, 'w') as f:
    f.write('/* tdc_embedded.h — built-in template pieces from the reference disk\n'
            ' * (article 2224_2). Generated by make_embedded.py — do not edit. */\n'
            '#ifndef TDC_EMBEDDED_H\n#define TDC_EMBEDDED_H\n\n'
            f'#define EMB_WIDTH_BITS {wbits}\n'
            f'#define EMB_WIDTH_PX   {int.from_bytes(par[62:64],"big")}\n'
            f'#define EMB_LAENGE_LEN {len(laenge)}\n'
            f'#define EMB_TRAILER_LEN {len(trailer)}\n\n')
    f.write(carr('emb_param88', par[:88]) + '\n\n')
    f.write(carr('emb_laenge', laenge) + '\n\n')
    f.write(carr('emb_trailer', trailer) + '\n\n#endif\n')
print(f'wbits={wbits} wpx={int.from_bytes(par[62:64],"big")} '
      f'laenge={len(laenge)}B trailer={len(trailer)}B laenge_block={laenge_blk} -> {OUT}')
